#!/usr/bin/env python3
"""Generate a module's string arrays for the DOS build (modules with word-aligned strings).

    python tools/strings.py FILE.c            show the block that would be written
    python tools/strings.py FILE.c --apply    write (or rewrite) it into the file

In most modules of the original every string starts at an even address (an odd-length
string is followed by a padding byte). Microsoft C 5.1 packs string literals byte by
byte, but places every data object, char arrays included, on an even address
(research: build/exp/T1.C). So in those modules the strings were data objects, and the
DOS build defines them as static char arrays, in DGROUP order:

    #if defined(TARGET_DOS16)
    #undef _TEXT
    #define _TEXT(addr, text) S_##addr
    static char S_0x96b4[] = "Player: ";
    ...
    #endif

u5d's code keeps its _TEXT(0x96b4, "Player: ") calls unchanged: in the DOS build they
name the array, elsewhere they stay literals. The block goes right after the #include
lines, and holds every _TEXT string of the module (one array per address), together
with the module's tables (D_xxxx definitions from the file, moved into the block) in
address order. The block is generated: edit the strings in the code, then rerun.
"""
import argparse, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import u5  # noqa: E402
import dgroup  # noqa: E402

BEGIN = '// BEGIN DGROUP (generated by tools/strings.py: module data in the original order)'
END = '// END DGROUP'


def collect(src):
    """{addr: (spelling of addr as written, literal)} for every _TEXT in src."""
    out = {}
    for m in dgroup.STR_RE.finditer(src):
        spell = re.search(r'0x[0-9a-fA-F]+', m.group(0)).group(0)
        a = int(spell, 16)
        lit = m.group(2).strip()
        if a in out and out[a][1] != lit:
            print('warning: two different strings at %04x: %s / %s' % (a, out[a][1], lit))
        spells = out.get(a, (set(), lit))[0]
        spells.add(spell)
        out[a] = (spells, lit)
    return out


def table_defs(src):
    """{addr: definition text} for D_xxxx definitions at file scope in src (outside functions)."""
    out = {}
    for m in re.finditer(r'^(?:static\s+)?[A-Za-z][\w\s\*]*?\b(D_([0-9a-f]{4})\w*)\s*(\[[^\]]*\])*\s*=', src, re.M):
        i, depth = m.start(), 0
        while i < len(src):
            c = src[i]
            if c in '{(':
                depth += 1
            elif c in '})':
                depth -= 1
            elif c == ';' and depth == 0:
                break
            i += 1
        end = src.index('\n', i) + 1
        out[int(m.group(2), 16)] = (m.start(), end, src[m.start():end].rstrip())
    return out


def strip_block(src):
    if BEGIN in src:
        a = src.index('#if defined(TARGET_DOS16)\n' + BEGIN) if ('#if defined(TARGET_DOS16)\n' + BEGIN) in src else src.index(BEGIN)
        b = src.index(END, a)
        b = src.index('#endif', b)
        b = src.index('\n', b) + 1
        src = src[:a] + src[b:]
    return src


def annotate(src):
    """Turn u5d's address comments (/*0x96c6*/ CLASS_LIST) into _TEXT(0x96c6, CLASS_LIST)
    inside functions and _STATIC_TEXT(...) at file scope, so the DOS build can map them."""
    import slots
    bodies = [(a, b) for _, a, b in slots.functions(src)]
    out, last = [], 0
    for m in dgroup.ANNOT_RE.finditer(src):
        if not dgroup.literal(m.group(2)):
            continue
        inside = any(a <= m.start() < b for a, b in bodies)
        out.append(src[last:m.start()])
        out.append('%s(0x%s, %s)' % ('_TEXT' if inside else '_STATIC_TEXT', m.group(1), m.group(2).strip()))
        last = m.end()
    out.append(src[last:])
    return ''.join(out)


def all_strings():
    """{addr: (spellings, literal, files)} for every addressed string in every module file."""
    out = {}
    for f in u5.MODULES:
        p = os.path.join(u5.SRC, f)
        if not os.path.exists(p):
            continue
        s = open(p, encoding='utf-8', errors='replace').read()
        for m in list(dgroup.STR_RE.finditer(s)) + list(dgroup.ANNOT_RE.finditer(s)):
            if not dgroup.literal(m.group(2)):
                continue
            spell = re.search(r'0x[0-9a-fA-F]+', m.group(0)).group(0)
            a = int(spell, 16)
            e = out.setdefault(a, (set(), m.group(2).strip(), set()))
            e[0].add(spell)
            e[2].add(f)
    return out


def build(src, cfile):
    src = annotate(strip_block(src))
    strs = collect(src)
    tabs = table_defs(src)
    # tables leave their old place and go into the block
    for a in sorted(tabs, key=lambda k: -tabs[k][0]):
        s, e, _ = tabs[a]
        src = src[:s] + src[e:]
    # every string inside the module's data belongs to it, wherever u5d writes it (vars.c's
    # tables point at strings of several array modules); one the module uses but which lies
    # outside its data belongs to another module and is declared extern
    allstr = all_strings()
    items_, _ = dgroup.build()
    run = dgroup.module_run(cfile, items_)
    extern = []
    for a in list(strs):
        if run and not run[0] <= a < run[1]:
            extern.append((a, strs.pop(a)[0]))
    if run:
        for a, (spells, lit, files) in allstr.items():
            if run[0] <= a < run[1] and a not in strs:
                strs[a] = (spells, lit)
    items = [(a, 'S', v) for a, v in strs.items()] + [(a, 'T', v[2]) for a, v in tabs.items()]
    lines = ['#if defined(TARGET_DOS16)', BEGIN, '#undef _TEXT', '#define _TEXT(addr, text) S_##addr',
             '#undef _STATIC_TEXT', '#define _STATIC_TEXT(addr, text) S_##addr']
    for a, spells in sorted(extern):
        lines.append('extern char S_%s[];' % sorted(spells)[0])
        for other in sorted(spells)[1:]:
            lines.append('#define S_%s S_%s' % (other, sorted(spells)[0]))
    for a, kind, v in sorted(items, key=lambda x: x[0]):
        if kind == 'S':
            spells, lit = v
            spells = set(spells) | allstr.get(a, (set(), None, None))[0]
            first = sorted(spells)[0]
            shared = allstr.get(a, (None, None, {cfile}))[2] - {cfile}
            lines.append('%schar S_%s[] = %s;' % ('' if shared else 'static ', first, lit))
            for other in sorted(spells)[1:]:
                lines.append('#define S_%s S_%s' % (other, first))
        else:
            lines.append(v)
    lines += [END, '#endif', '']
    block = '\n'.join(lines)
    # tables used elsewhere must exist in the native build too: keep a native copy
    native = [v[2] for v in sorted(tabs.items())]
    if native:
        block += '\n#if !defined(TARGET_DOS16)\n' + '\n'.join(native) + '\n#endif\n'
    incs = list(re.finditer(r'^#include .*\n', src, re.M))
    at = incs[-1].end() if incs else 0
    return src[:at] + '\n' + block + src[at:]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('file')
    ap.add_argument('--apply', action='store_true')
    a = ap.parse_args()
    p = a.file if os.path.exists(a.file) else os.path.join(u5.SRC, a.file)
    src = open(p, encoding='utf-8', newline='').read()
    new = build(src, os.path.basename(p))
    if a.apply:
        open(p, 'w', encoding='utf-8', newline='').write(new)
        print('wrote the DGROUP block of %s' % p)
    else:
        i = new.index(BEGIN)
        print(new[i:new.index(END, i) + len(END)])


if __name__ == '__main__':
    main()
